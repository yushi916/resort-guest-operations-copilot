alter table public.resort_documents enable row level security;
alter table public.resort_operations_requests enable row level security;
alter table public.resort_service_bookings enable row level security;

revoke all on table public.resort_documents from anon, authenticated;
revoke all on table public.resort_operations_requests from anon, authenticated;
revoke all on table public.resort_service_bookings from anon, authenticated;

grant usage on schema public to service_role;
grant all on table public.resort_documents to service_role;
grant all on table public.resort_operations_requests to service_role;
grant all on table public.resort_service_bookings to service_role;
grant usage, select on all sequences in schema public to service_role;
grant execute on function public.match_resort_documents(vector, integer, jsonb)
  to service_role;

